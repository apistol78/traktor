#include "Core/Date/DateTime.h"
#include "Blog/BlogData.h"

namespace traktor::blog
{
	namespace
	{

uint64_t at(uint8_t month, uint8_t day, uint8_t hour, uint8_t minute)
{
	return DateTime(2026, month, day, hour, minute, 0).getSecondsSinceEpoch();
}

	}

Blog createSampleBlog()
{
	Blog blog;

	blog.posts.push_back({ L"Welcome to the Webber blog", L"apistol", at(10, 12, 9, 30),
		L"Webber is a small C++ library for building web applications *entirely on the server*. Pages are trees of widgets; the browser only displays them and reports clicks.\n"
		L"\n"
		L"This blog and the forum next to it are both built with Webber. Everything you see is generated by the server and kept in sync as you click around.\n"
		L"\n"
		L"Use the links in the top bar to move between the **blog** and the **forum**. Posts are written in Markdown; log in as an admin, open one and press *Edit* to see how."
	});

	blog.posts.push_back({ L"How the page updates without reloading", L"Alice", at(10, 26, 14, 5),
		L"Every session owns a tree of widgets. When the page is loaded the tree is turned into an HTML document and sent to the browser as a whole.\n"
		L"\n"
		L"After that, each click goes through these steps:\n"
		L"\n"
		L"1. The click is sent to the server together with the contents of all text fields.\n"
		L"2. The server applies the input, runs the click handler and builds the document again.\n"
		L"3. The new document is compared with the previous one, and only the parts that changed are sent back.\n"
		L"\n"
		L"> A small script in the page replaces those parts, so the rest of the page, including anything you have typed, stays as it is."
	});

	blog.posts.push_back({ L"Hardening the HTTP server", L"Bob", at(11, 2, 18, 40),
		L"The HTTP server now collects requests from all connections at the same time, so a slow or idle client can no longer hold up everybody else. Headers, request bodies and idle connections all have limits.\n"
		L"\n"
		L"## Requests\n"
		L"\n"
		L"- Clicks must carry a custom `X-Webber` header which other sites cannot send.\n"
		L"- The session cookie is hidden from scripts.\n"
		L"- Only session ids issued by the server are accepted.\n"
		L"\n"
		L"## Responses\n"
		L"\n"
		L"Responses declare their content type and cannot be shown inside frames on other sites:\n"
		L"\n"
		L"```\n"
		L"X-Content-Type-Options: nosniff\n"
		L"Content-Security-Policy: frame-ancestors 'none'\n"
		L"```"
	});

	return blog;
}

}
